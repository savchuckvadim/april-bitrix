// Прямой путь, а не барель shared/metrics: врезка должна быть видна в
// импортах файла и подменяться тестом одной строкой.
import { countReportOutcome } from '@/modules/shared/metrics/lib/business-metrics';
import type { ReportOutcomeLabel } from '@/modules/shared/metrics/lib/metric-contract';

import { OUTBOX_ENVELOPE_STATE, type OutboxEnvelope } from './outbox-envelope';

/**
 * ТЕРМИНАЛЬНАЯ СУДЬБА ОТЧЁТА — ровно один инкремент на конверт.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ПОПЫТОК. Счётчик попыток
 * (`event_sales_report_delivery_attempts_total`) растёт на каждое обращение
 * к цели: одна сессия при молчащем бэке даёт три сетевые попытки плюс
 * фолбэк-пас, а дренаж повторяет то же самое каждую минуту — пять
 * застрявших отчётов дают под тысячу инкрементов в час. По такому счётчику
 * доля доставленных не считается: знаменатель растёт от одних лишь ретраев,
 * и «всё плохо» выглядит на графике как «стало лучше». Здесь считается
 * ДРУГОЕ: чем закончился отчёт менеджера.
 *
 * ПОЧЕМУ ОТМЕТКА В КОНВЕРТЕ, А НЕ ФЛАГ В ПАМЯТИ. Претендентов посчитать
 * исход много и живут они в разных местах: поллинг FlowWatch
 * (`markDelivered`/`markFailed`), сверка статуса в дренаже, прямое
 * исполнение в движке, досылка хвоста, соседняя вкладка того же портала,
 * новая сессия после перезагрузки фрейма. Общего у них ровно одно — конверт
 * в IndexedDB. Отметка лежит там же и переживает всё перечисленное.
 *
 * ЧЕГО ОТМЕТКА НЕ ЛОВИТ, честно. (1) Две вкладки, прочитавшие конверт
 * ОДНОВРЕМЕННО до записи любой из них, посчитают исход дважды — окно в
 * несколько миллисекунд против отчёта, который живёт минутами; сужают его
 * ещё и гварды состояния (`markDelivered` выходит на уже погашенном
 * конверте). (2) Сквозное хранилище (kind `none`, отказ квоты) отметку не
 * сохранит — тогда конверт живёт только в памяти вкладки и вместе с ней
 * умирает, пересчитать его некому. Оба случая дают завышение, а не занижение,
 * и оба заметны как расхождение с `event_sales_send_total`.
 */

/** Терминальный исход уже посчитан — второй раз конверт не считаем. */
export const isReportOutcomeCounted = (envelope: OutboxEnvelope): boolean =>
    envelope.outcomeCounted === true;

/**
 * Посчитать терминальный исход конверта и вернуть конверт С ОТМЕТКОЙ — его и
 * надо записать в хранилище. Уже посчитанный конверт возвращается как есть, и
 * метрика не растёт.
 *
 * Возврат конверта, а не «запиши сам»: запись исхода в хранилище всё равно
 * делает вызывающий, и лишний асинхронный поход в IndexedDB здесь означал бы
 * вторую гонку поверх той, что уже описана в шапке файла.
 */
export const markReportOutcome = (
    envelope: OutboxEnvelope,
    outcome: ReportOutcomeLabel,
): OutboxEnvelope => {
    if (isReportOutcomeCounted(envelope)) {
        return envelope;
    }
    countReportOutcome({ outcome, domain: envelope.domain });

    return { ...envelope, outcomeCounted: true };
};

/**
 * Конверт, закрытый ПРЯМЫМ исполнением: `delivered` — терминал (отчёт
 * проведён браузером целиком), `partial` — ещё нет. У partial служебная часть
 * не проведена, её везёт пас досылки, и терминальным исходом такой конверт
 * станет только когда хвост доедет. Считать его «проведённым» сейчас значило
 * бы записать в успех отчёт без KPI, движений сделок и элементов смартов.
 */
export const markDirectExecutionOutcome = (
    envelope: OutboxEnvelope,
): OutboxEnvelope =>
    envelope.state === OUTBOX_ENVELOPE_STATE.delivered
        ? markReportOutcome(envelope, 'delivered')
        : envelope;
