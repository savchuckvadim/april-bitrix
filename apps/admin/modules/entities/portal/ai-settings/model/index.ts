/**
 * Настройки AI-отчётности по звонкам на портал: типы — из сгенерированного
 * orval-клиента (бэк: back/libs/portal-lib/store/ai-settings, ручки
 * GET/PUT /api/admin/portal/{portalId}/ai-settings).
 *
 * КЛЮЧЕВОЙ ИНВАРИАНТ: `null` в любом поле = «на портале не задано», значение
 * берётся из глобальных env приложения event-sales. Поэтому форма различает
 * «как глобально» (null) и явные значения.
 */
export type PortalAiSettings = PortalAiSettingsResponseDto;

/** PUT: отсутствующее поле не трогается, явный null сбрасывает на глобальное. */
export type PortalAiSettingsUpdate = UpdatePortalAiSettingsDto;

/** Редактируемые поля формы (без служебного lastScanAt). */
export type PortalAiSettingsField = keyof PortalAiSettingsUpdate;

