/**
 * Номера и заголовки наборов в документе. Номер набора — единственный ключ,
 * по которому бэк связывает строки таблицы цен и наполнение набора: у строк он
 * лежит в `setId`, у наполнения в `setNumber`. Оба места берут номер отсюда.
 */

/** Номер общего набора: `setId` его строк */
export const GENERAL_SET_NUMBER = 0;

/**
 * Номер набора для сравнения: нумерация с 1 по порядку наборов в сделке
 * (`index` — позиция в `rowSet.alternative`). Набор без строк номер не теряет:
 * следующие наборы не сдвигаются.
 */
export const alternativeSetNumber = (index: number): number => index + 1;

/**
 * Заголовок набора для сравнения: «Набор N». Бэк печатает в таблице цен такой
 * же заголовок по номеру набора (`productSetTitle` по `setId` строк) и с
 * заголовком из `alternativeComplects` не сверяет, поэтому формула здесь и там
 * одна.
 */
export const alternativeSetTitle = (setNumber: number): string => `Набор ${setNumber}`;
