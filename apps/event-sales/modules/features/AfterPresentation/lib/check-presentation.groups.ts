import type { CheckPresentationItem } from '../type/check-presentation-type';

/**
 * Раскладка опросника по колонкам и категориям «Пяти К».
 *
 * После переделки 01.09.2026 категория И ЕСТЬ поле: девять вопросов
 * схлопнулись в пять блоков по теме, и заголовок блока («КЛИЕНТ») уже
 * называет категорию. Отдельная полоса-разделитель над единственным
 * вопросом группы была бы шумом, поэтому группировка теперь тождественна
 * заголовку, а срезать из заголовка нечего.
 *
 * Функции оставлены: на них стоит раскладка по колонкам (левая — «Хвост»,
 * правая — «5К») и формат комментария, а вернуть подгруппы внутри блока
 * портальный каталог анкет может в любой момент.
 */

const FIVE_K_PREFIX = 'op_5k_';

/** Вопрос «Пяти К» — правая колонка окна. */
export const isFiveKCode = (code: string): boolean =>
    code.startsWith(FIVE_K_PREFIX);

/**
 * Категория вопроса «Пяти К»; не 5К — null.
 *
 * Теперь у каждого блока своя категория и ровно один вопрос, поэтому
 * отдельного имени группы нет: его роль играет заголовок блока.
 */
export const getFiveKGroup = (_code: string): string | null => null;

/**
 * Заголовок для лейбла.
 *
 * Раньше у вопросов 5К срезался префикс категории («КЛИЕНТ: Что хочет?» →
 * «Что хочет?»), потому что категорию показывала полоса-разделитель. Теперь
 * заголовок И ЕСТЬ категория, и резать нечего — прежний срез оставил бы от
 * «КЛИЕНТ» пустую строку.
 */
export const getDisplayTitle = (item: CheckPresentationItem): string =>
    item.title;
