/** «короче 300 сек»; порог не пришёл — «короче порога длительности». */
export const aiPulseShortWord = (minDurationSec: number | null): string =>
    minDurationSec === null
        ? 'короче порога длительности'
        : `короче ${minDurationSec} сек`;

/**
 * Доля словами: до половины — «1 из 5», больше — «7 из 10»; ноль — «ни
 * одного». Для быстрого чтения рядом с процентом.
 */
export const aiPulseRatioWords = (share: number): string => {
    if (!(share > 0)) return 'ни одного';
    if (share <= 0.5) return `1 из ${Math.max(2, Math.round(1 / share))}`;
    return `${Math.min(10, Math.round(share * 10))} из 10`;
};

