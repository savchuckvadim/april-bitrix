import { buildTotalRow, type KRow, type RowSet } from '../../row-set';

/**
 * Строка «Итого» документов (КП, договор, отчёт о поставке, заявка поставки).
 *
 * Итог собирается по всему общему набору, и свёрнутому, и развёрнутому:
 * имена строк идут через « + », цены складываются (как в легаси), ручная
 * цена итога набора (set.totalPrice) имеет приоритет. Роль и ссылки на
 * комплект, договор и поставку берутся у главной строки: итог документа
 * адресуется главному комплекту, даже когда главная строка стоит в наборе
 * второй или дальше, и легаси-признак `id === 0` остаётся за ней.
 *
 * Пустой набор даёт главную строку без изменений.
 */
export const docTotalRow = (general: RowSet, main: KRow): KRow => {
    const total = buildTotalRow(general);
    if (!total) return main;
    return { ...total, role: main.role, refs: main.refs };
};
