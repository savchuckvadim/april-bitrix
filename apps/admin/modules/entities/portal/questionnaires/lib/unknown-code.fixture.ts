/**
 * Патч со значением, кода которого сгенерированный контракт НЕ знает —
 * ТОЛЬКО для тестов.
 *
 * Реестр бэка расширяется раньше, чем прогоняется orval: по сети приезжают
 * коды вне union-ов, и раздел обязан показывать их как есть, а не пустотой.
 * Именно это правило и проверяют такие случаи.
 *
 * Собрать такой патч типами нельзя — в том и смысл union-ов: редактор не
 * должен уметь набрать неисполнимое значение. Поэтому проверки строят его
 * здесь, и приведение имитирует ровно сеть: ответ бэка, который в
 * рантайме шире, чем контракт, по которому собран фронт.
 */
export const unknownCode = <T>(patch: unknown): T => patch as T;
