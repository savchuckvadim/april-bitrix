/**
 * Всплывающая подсказка: вопрос и одно действие.
 *
 * Приложение знает про клиента больше, чем видно на экране: что ИНН не
 * записан, что нашлись пересечения, что у заявки нет живой сделки. Прятать
 * это в карточки, до которых надо доскроллить, значит надеяться на
 * внимательность. Прятать в предупреждения без действия — вдвойне: менеджер
 * видит проблему, но не понимает, что нажать.
 *
 * Поэтому подсказка — это ровно вопрос и кнопка, которая его закрывает. За
 * кнопкой стоит серверный хук (поиск дублей, преобразование заявки в работу)
 * или локальное действие; подсказка сама по себе ничего не решает.
 */

export type ActionPromptTone = 'info' | 'warning' | 'success';

export interface ActionPrompt {
    /** Стабильный id: по нему подсказка гасится «позже» до перезагрузки. */
    id: string;
    /** Вопрос человеку, а не название состояния. */
    question: string;
    /** Пояснение под вопросом: почему спрашиваем и что будет. */
    hint?: string;
    /** Надпись на кнопке — глагол: «Записать», «Искать глубже». */
    actionLabel: string;
    tone: ActionPromptTone;
    /**
     * Чем меньше, тем раньше показываем. Одновременно на экране живёт ОДНА
     * подсказка: очередь из трёх карточек — это уже не подсказка, а форма.
     */
    priority: number;
    run: () => void;
}

/** Первая по важности из ещё не погашенных. */
export const pickActionPrompt = (
    prompts: ActionPrompt[],
    dismissedIds: string[],
): ActionPrompt | null => {
    const available = prompts
        .filter(prompt => !dismissedIds.includes(prompt.id))
        .sort((a, b) => a.priority - b.priority);
    return available[0] ?? null;
};

/** Порядок важности — данные, чтобы не разъезжался по местам вызова. */
export const ACTION_PROMPT_PRIORITY = {
    /** Мешает продаже прямо сейчас. */
    BLOCKING: 10,
    /** Может дорого стоить, но работать не мешает. */
    RISK: 20,
    /** Просто полезно. */
    HELPFUL: 30,
} as const;
