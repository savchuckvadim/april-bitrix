// Прямой путь, а не барель слайса: барель тянет thunk с транспортом
// (сгенерированный клиент каталога), движку чек-листов он не нужен.
import type {
    QuestionnaireDef,
    QuestionnaireItem,
} from '@/modules/entities/Questionnaire/model/questionnaire.type';

/**
 * Чек-лист pbx-полей — «информация, которую можно получить только от
 * менеджера»: вопросы, которые надо показать (с текущим значением из CRM) и
 * заполнить в конкретный момент работы.
 *
 * СОСТАВ ЗАДАЁТ ПОРТАЛ. Каталог анкет живёт в сторе
 * (`state.questionnaireCatalog`, слайс `entities/Questionnaire`): админ
 * собирает анкеты из полей, заведённых в Битриксе руками, бэк отдаёт
 * скомпилированный каталог во фрейм. Своих типов набора и вопроса у движка
 * больше нет — он исполняет доменные `QuestionnaireDef`/`QuestionnaireItem`.
 *
 * Каталога нет (миграция не накатана, 500, таймаут) — в сторе стоит
 * встроенный `FALLBACK_CATALOG`, и движок работает ровно как раньше.
 *
 * Compile-time union'ов (`ChecklistId`, `ChecklistTrigger`) здесь нет
 * намеренно: коды анкет и виды условий приходят по сети, и защищать от
 * опечатки обязаны рантайм-нормализатор каталога и валидация на бэке, а не
 * тип на границе сети.
 */

/** Набор вопросов = анкета портального каталога. */
export type ChecklistDef = QuestionnaireDef;

/** Вопрос набора = пункт анкеты. */
export type ChecklistFieldDef = QuestionnaireItem;

/**
 * Вопрос вместе с анкетой, которая его задаёт.
 *
 * Ключ ответа — пара «анкета : вопрос», поэтому одного описания вопроса для
 * чтения и записи значения мало: движок везде носит ссылку целиком.
 */
export interface ChecklistFieldRef {
    /**
     * `${код анкеты}:${код вопроса}` — ключ значения, черновика и таймера
     * автосохранения (см. `answerKey` слайса каталога анкет).
     */
    answerKey: string;
    def: ChecklistFieldDef;
}
