/**
 * Формат события метрики — ЕДИНСТВЕННЫЙ контракт между браузером и сервером.
 *
 * Зачем формат вообще: события происходят в браузере (бут, отправка отчёта,
 * спрятанный вопрос), а prom-client живёт в процессе Next-сервера — сам в
 * реестр клиентский замер не попадёт. Путь такой: браузер копит события →
 * шлёт пачкой на свой же домен (`/api/metrics/report`) → маршрут приёма
 * инкрементит счётчики в реестре → Prometheus скрейпит `/api/metrics`.
 *
 * Формат намеренно минимальный: имя, метки, значение. Ничего про время
 * (сервер инкрементит в момент приёма — метрики не про точную хронологию),
 * ничего про пользователя (запрет на идентификаторы — см. metric-contract).
 *
 * Совместимость: вкладка во фрейме живёт сутками и после релиза продолжает
 * слать СТАРУЮ форму. Поэтому поля только добавляются и только
 * необязательными, а версия пачки существует, чтобы несовместимую правку
 * можно было отличить, а не угадать.
 */

/** Версия формата пачки. Меняется только при несовместимой правке. */
export const METRIC_BATCH_VERSION = 1;

/**
 * Имена бизнес-метрик. Стиль Prometheus: snake_case, префикс приложения,
 * единица измерения в имени (`_seconds`), `_total` у счётчиков.
 */
export const METRIC = {
    /**
     * ПЕРВАЯ ЗАГРУЗКА, разложенная по фазам: время от НАВИГАЦИИ документа
     * (timeOrigin) до каждой фазы бута (метка `phase` — фазы из
     * boot-phases.ts). Отсчёт именно от навигации: TTFB, бандл и гидрация —
     * это ожидание менеджера, и прятать его в ноль было бы враньём.
     */
    bootPhase: 'event_sales_boot_phase_seconds',
    /**
     * ГЛАВНАЯ ЦИФРА владельца: сколько прошло от навигации документа до
     * появления списка дел. Отдельной метрикой, а не выборкой по метке,
     * чтобы на дашборде это был один график без фильтра.
     */
    bootToTasks: 'event_sales_boot_to_tasks_seconds',
    /**
     * ПОПЫТКИ ДОСТАВКИ: каждое обращение к цели (`outcome` × `target`) плюс
     * сверка статуса в дренаже. Ретраи бэкоффа и повторы дренажа считаются
     * КАЖДЫЙ — это частота попыток, а не судьба отчёта, и знаменателем доли
     * успеха этот счётчик быть не может (для неё есть `reportOutcome`).
     */
    deliveryAttempt: 'event_sales_report_delivery_attempts_total',
    /**
     * СУДЬБА ОТЧЁТА — ровно ОДИН терминальный исход на конверт за всю его
     * жизнь (`outcome`: проведён / отвергнут сервером / проведён не целиком /
     * застрял навсегда). Именно этот счётчик отвечает на «где теряются
     * отчёты»: `event_sales_send_total` — сколько отправок началось, сумма
     * исходов — сколько из них чем-то закончилось, разница — сколько висит.
     */
    reportOutcome: 'event_sales_report_outcome_total',
    /**
     * ОСТАТОК КОНВЕРТОВ, увиденный ОДНОЙ вкладкой по итогу её прогона
     * дренажа (метка `state`). Не сумма по порталу — см. help метрики.
     */
    outboxBacklog: 'event_sales_outbox_backlog_last_seen_envelopes',
    /** СПРЯТАННЫЕ ВОПРОСЫ анкеты: причина (`reason`) и канал (`channel`). */
    checklistQuestionHidden: 'event_sales_checklist_question_hidden_total',
    /** ОТПРАВКИ ВСЕГО: отчёты и недозвоны (метка `kind`). */
    send: 'event_sales_send_total',
} as const;

export type MetricName = (typeof METRIC)[keyof typeof METRIC];

/** Что просит записать вызывающий код. */
export interface MetricEvent {
    name: MetricName;
    /**
     * Метки. Лишние ключи маршрут выбрасывает, неизвестные значения
     * схлопывает — см. serializeMetricEvent.
     */
    labels?: Record<string, string>;
    /**
     * Счётчику — приращение (не задано = 1), гистограмме и gauge —
     * наблюдение в единицах ИМЕНИ метрики (`_seconds` → секунды).
     */
    value?: number;
}

/** То, что реально уходит по проводу: уже проверенное и нормализованное. */
export interface SerializedMetricEvent {
    name: MetricName;
    /** Все объявленные метки метрики, без пропусков (иначе плывут серии). */
    labels: Record<string, string>;
    value: number;
}

/** Тело POST на маршрут приёма. */
export interface MetricBatchBody {
    v: typeof METRIC_BATCH_VERSION;
    events: SerializedMetricEvent[];
}
