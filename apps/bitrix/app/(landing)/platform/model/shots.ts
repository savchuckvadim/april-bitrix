/**
 * Реестр кадров раздела — одновременно задание на съёмку (SHOTS.md).
 *
 * Снятый файл кладётся в `public/platform/shots/<id>.png` (видео —
 * `public/platform/video/<id>.mp4` и постер `<id>.jpg`) и подхватывается
 * сам (lib/shot-files.ts); `src` здесь — только если файл лежит иначе.
 * Пока файла нет, на проде кадра нет вовсе, а при разработке на его месте
 * рамка с `what` и `where`.
 *
 * `caption` видит клиент — пишем выгоду, а не название экрана.
 * `aiScreenIds` — тот же кадр нужен разделу /ai: снять один раз.
 */

export type PlatformShotKind = 'image' | 'video';

/** 1 — без него страница слабая; 2 — шаги «как работает»; 3 — галерея. */
export type PlatformShotPriority = 1 | 2 | 3;

export interface PlatformShotSpec {
    kind: PlatformShotKind;
    priority: PlatformShotPriority;
    /** Где снимать: интерфейс и место в нём. */
    where: string;
    /** Что должно попасть в кадр. */
    what: string;
    /** Подпись под кадром на сайте. */
    caption: string;
    src?: string;
    poster?: string;
    aiScreenIds?: readonly string[];
}

/** Ключи остаются литералами (тип PlatformShotId), значения — общей формы. */
const defineShots = <T extends Record<string, PlatformShotSpec>>(
    shots: T,
): Record<keyof T, PlatformShotSpec> => shots;

