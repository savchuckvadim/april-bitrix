/**
 * СНЯТИЕ batch-экранирования перед отдачей значений в b24jssdk.
 *
 * ПОЧЕМУ ЭТО ВООБЩЕ ЕСТЬ. Экранирование — свойство ТРАНСПОРТА, а не текста
 * (правило в шапке `shared/batch/batch-text.ts`). Флоу — один и тот же код на
 * сервере и в браузере — готовит текст для транспорта, который склеивает
 * query-строку `cmd` РУКАМИ и вклеивает значения СЫРЫМИ: там `%0A`, `%25`,
 * `%2B`, `%26` обязаны приехать уже экранированными, потому что Битрикс
 * декодирует строку ОДИН раз.
 *
 * Браузерный провод другой. `@workspace/bitrix` копит команды СТРУКТУРОЙ
 * (`{ method, params }`), а строит из них `cmd` уже b24jssdk —
 * `qs.stringify(command.query)` с `encode: true`. Он закодирует всё сам,
 * включая наш `%`: `...X%0AГотов` уехало бы как `...X%250AГотов`, Битрикс
 * декодировал бы это ОДИН раз, и в поле легло бы ЛИТЕРАЛЬНОЕ `%0A` вместо
 * переноса. Один отчёт давал бы разное содержимое поля в зависимости от того,
 * кто его исполнил — сервер или вкладка.
 *
 * ЧТО ДЕЛАЕМ. Возвращаем текст в ПЛОСКИЙ вид — ровно тот, который Битрикс
 * получил бы после своего единственного декодирования на серверном пути.
 * Дальше SDK кодирует его сам, и оба пути сходятся байт в байт.
 *
 * ПОРЯДОК СНЯТИЯ — строго обратный порядку {@link toBatchSafeText}
 * (`%` → `+` → `&` → перенос), то есть перенос → `&` → `+` → `%`. Иначе
 * литерал, который менеджер набрал руками, разъехался бы: `%26` уезжает
 * как `%2526`, и снятие `%25` ПЕРВЫМ дало бы `%26`, которое следующий шаг
 * превратил бы в `&`. При обратном порядке `%2526` доживает до последнего
 * шага целиком и честно становится обратно `%26`.
 *
 * ГРАНИЦА ПРИМЕНЕНИЯ — только `batch.*`. Обычные `call.*` идут мимо
 * query-склейки, и флоу отдаёт им плоский текст изначально
 * (`imNotifySystemAdd`), — снимать там нечего.
 */

/** Пары «escape → плоский символ» в порядке, обратном экранированию. */
const DECODE_STEPS: ReadonlyArray<readonly [RegExp, string]> = [
    [/%0A/g, '\n'],
    [/%26/g, '&'],
    [/%2B/g, '+'],
    [/%25/g, '%'],
];

/** Один текст: batch-вид → плоский. */
export const decodeBatchEscapedText = (text: string): string =>
    DECODE_STEPS.reduce(
        (acc, [pattern, plain]) => acc.replace(pattern, plain),
        text,
    );

/**
 * Значение команды целиком: строки разворачиваются, структура сохраняется.
 *
 * Вход не мутируется — возвращаются новые объекты/массивы: тот же payload
 * может лежать в замыкании группового буфера и материализоваться отдельно от
 * этого вызова.
 *
 * Всё, что не строка, не массив и не простой объект (числа, булевы, Date,
 * null), отдаётся как есть: `$result[...]`-чейны и id ни одного из четырёх
 * escape'ов не содержат, поэтому проход по ним безвреден.
 */
export const decodeBatchEscapes = <T>(value: T): T => {
    if (typeof value === 'string') {
        return decodeBatchEscapedText(value) as unknown as T;
    }
    if (Array.isArray(value)) {
        return value.map(item => decodeBatchEscapes(item)) as unknown as T;
    }
    if (value !== null && typeof value === 'object') {
        const proto = Object.getPrototypeOf(value);
        // Простой объект-словарь параметров; экземпляры классов (Date и т.п.)
        // не разбираем — это не носители текста команды.
        if (proto !== Object.prototype && proto !== null) return value;
        const out: Record<string, unknown> = {};
        for (const [key, item] of Object.entries(
            value as Record<string, unknown>,
        )) {
            out[key] = decodeBatchEscapes(item);
        }
        return out as unknown as T;
    }
    return value;
};
