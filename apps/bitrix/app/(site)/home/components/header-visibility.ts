/**
 * На каких страницах хедер видно сразу, без прокрутки.
 *
 * По умолчанию хедер лендинга `fixed` и скрыт наверху: иначе он перекрыл бы
 * первый экран, который под него места не оставляет. Но на страницах,
 * которые открывают по прямой ссылке, это читается как сбой вёрстки —
 * сначала хедера нет, потом он выезжает при прокрутке.
 *
 * Такие страницы перечислены здесь, а не разбросаны по компонентам, чтобы
 * правило было в одном месте. Страница обязана сама оставлять отступ
 * сверху (хедер места в потоке не занимает).
 */

/** Префиксы путей, где хедер показываем всегда. */
const ALWAYS_VISIBLE_PREFIXES = [
    // КП действующему клиенту: открывается по персональной ссылке.
    '/renewal',
] as const;

/** Показывать ли хедер на этом пути сразу, не дожидаясь прокрутки. */
export function isAlwaysVisiblePath(pathname: string | null): boolean {
    if (!pathname) return false;
    return ALWAYS_VISIBLE_PREFIXES.some(
        prefix => pathname === prefix || pathname.startsWith(`${prefix}/`),
    );
}
