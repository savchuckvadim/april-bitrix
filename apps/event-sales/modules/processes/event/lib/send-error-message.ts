/**
 * Текст ошибки отправки для экрана финиша.
 *
 * Причина отказа приходит от бэка по-русски и написана ИМЕННО для менеджера
 * (docblock гарда: «400 из POST фронт показывает менеджеру баннером»). До
 * 15.09 фронт её выбрасывал в `console.error`, а на экран выводил одну и ту
 * же фразу «Не удалось отправить отчёт» — менеджер видел тупик, а настоящую
 * причину («Продажа: заполните сумму сделки и дату первой оплаты») можно
 * было достать только из devtools.
 *
 * Префикс `HTTP 400:` сборщик detail'а ставит для логов — на экране он
 * лишний шум, поэтому снимается.
 */
const HTTP_PREFIX = /^HTTP\s+\d{3}:\s*/;

/**
 * Сообщения транспорта, а не бэка: они появляются, когда тела ответа нет
 * вовсе, и менеджеру не говорят ничего — вместо них честнее общая фраза.
 */
const TRANSPORT_NOISE = [
    /^request failed with status code/i,
    /^network error$/i,
    /^timeout\b/i,
    /^canceled$/i,
    /^aborted$/i,
];

/** Общий хвост: главное — работа менеджера никуда не делась. */
const TAIL = 'Данные никуда не делись — можно повторить.';

export const toSendErrorMessage = (detail?: string): string => {
    const reason = (detail ?? '')
        .replace(HTTP_PREFIX, '')
        .trim()
        .replace(/[.\s]+$/, '');

    const isHuman =
        reason.length > 0 &&
        !TRANSPORT_NOISE.some(pattern => pattern.test(reason));

    return isHuman
        ? `Не удалось отправить отчёт: ${reason}. ${TAIL}`
        : `Не удалось отправить отчёт. ${TAIL}`;
};
