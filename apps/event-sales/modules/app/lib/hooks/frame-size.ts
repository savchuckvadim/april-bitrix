/**
 * Минимальный размер фрейма во встройке-вкладке.
 *
 * Подгонка под контент сама по себе на маленьких мониторах даёт щель: блок
 * в карточке узкий, контент в него ужимается, подгонка честно повторяет эту
 * узкую высоту — и так по кругу. Пол разрывает круг.
 *
 * Числа НЕ считаются от `window.screen`: экран — это физический монитор, он не
 * знает ни про масштабирование системы, ни про то, что окно браузера занимает
 * половину рабочего стола. Именно на этом ползла ширина в старом конструкторе
 * (`resizeWindow(screen.width * 0.73, screen.height * 0.9)`): на одной машине
 * попадало в блок, на другой мимо. Фиксированный пол ведёт себя одинаково
 * везде, а сверху размер всё равно задаёт контент.
 */
export const FRAME_MIN_HEIGHT = 600;

