/**
 * Что делать, когда предложение не открылось.
 *
 * Правило одно для страницы и для PDF: иначе клиент по одной ссылке попал
 * бы на главную, а по соседней увидел бы ошибку.
 */
import type { RenewalFetchFailure } from './renewal-offer.api';

/**
 * Уводить ли на главную.
 *
 * `gone` — ссылка отозвана, истекла или не существует: показывать нечего,
 * ведём на сайт. Все три случая ведут в одно место, поэтому перебором
 * токенов нельзя узнать, какие ссылки существуют.
 *
 * `error` — сбой на нашей стороне: ссылка, скорее всего, живая, и уводить
 * клиента нельзя. Иначе он решит, что предложение отменили, хотя надо
 * просто зайти позже.
 */
export function shouldRedirectHome(reason: RenewalFetchFailure): boolean {
    return reason === 'gone';
}

/**
 * Куда уводим недействующую ссылку.
 *
 * Сразу `/home`, а не `/`: middleware всё равно перебрасывает корень на
 * `/home` безусловно, и через корень клиент получил бы лишний переход.
 */
export const RENEWAL_FALLBACK_PATH = '/home';
