/**
 * Вердикт по текущей конфигурации — одна строка, которую читает заказчик.
 *
 * Плюсы и минусы каждой схемы взяты дословно из
 * `docs/product/polairities/where_is_managers_flow.md`. Ничего не выдумываем:
 * если у выбора есть цена, показываем её формулировкой самого документа.
 */

import { plural } from '../lib/plural.util';
import { ProcessDefinition, ProcessModel } from '../types';

export type VerdictTone = 'success' | 'warning' | 'destructive';

export interface ProcessVerdict {
    tone: VerdictTone;
    /** Главное: что происходит с процессом при этих ползунках. */
    headline: string;
    /** Где менеджер работает — отдельной строкой, это самый частый вопрос. */
    workplace: string;
    /** Чем приходится платить за такой выбор. Пусто — платить нечем. */
    price: string[];
    /** Выгода такого выбора. */
    gain: string[];
}

const stageLabel = (
    definition: ProcessDefinition,
    index: number,
): string | null => definition.stages[index]?.label ?? null;

const workplaceLine = (model: ProcessModel): string => {
    const { inLead, inDeal, isSplit } = model.callsApp;

    if (isSplit) {
        return 'Приложение «Звонки» открывается и из лида, и из сделки. Форма одна и та же, она же синхронизирует статусы между ними.';
    }
    if (inLead) {
        return 'Приложение «Звонки» работает в карточке лида. Стадии сделок при этом менеджер двигает руками.';
    }
    if (inDeal) {
        return 'Приложение «Звонки» работает в сделке. У менеджера всегда один интерфейс.';
    }
    return 'Рабочего места у менеджера не остаётся: процесс не ведёт ни лид, ни сделка.';
};

export const buildVerdict = (
    definition: ProcessDefinition,
    model: ProcessModel,
): ProcessVerdict => {
    const workplace = workplaceLine(model);

    if (model.relation === 'gap') {
        return {
            tone: 'destructive',
            headline: `Разрыв: ${model.gapCount} ${plural(
                model.gapCount,
                'стадию',
                'стадии',
                'стадий',
            )} не ведёт ни лид, ни сделка.`,
            workplace,
            price: [
                'Часть пути клиента не попадает ни в один учёт — эти стадии не отчитываются и не видны в отчётах.',
            ],
            gain: [],
        };
    }

    if (model.relation === 'duplicate') {
        return {
            tone: 'warning',
            headline:
                'Полное дублирование: весь процесс живёт одновременно в лиде и в сделке.',
            workplace,
            price: [
                'Надо работать в двух местах.',
                'Дополнительная ответственность за дубли-недубли.',
                'Каждое событие приходится сводить между двумя сущностями — это и делает приложение «Звонки».',
            ],
            gain: [
                'Неизвестные и необработанные заявки остаются в одном месте.',
                'Ни один вход в процесс не теряется.',
            ],
        };
    }

    if (model.relation === 'overlap') {
        const from = stageLabel(definition, model.dealStart);
        const to = stageLabel(definition, model.leadEnd);

        return {
            tone: 'warning',
            headline: (() => {
                const stages = `${model.overlapCount} ${plural(
                    model.overlapCount,
                    'стадии',
                    'стадиях',
                    'стадиях',
                )}`;

                return from && to && from !== to
                    ? `Перекрытие на ${stages} — от «${from}» до «${to}» работают оба контура.`
                    : from
                      ? `Перекрытие на ${stages}: «${from}» ведут оба контура.`
                      : `Перекрытие на ${stages}: обе сущности ведут одни и те же шаги.`;
            })(),
            workplace,
            price: [
                'Надо работать в двух местах: воронка начинает рваться — но это сглаживает приложение «Звонки».',
                'Дополнительная ответственность за дубли-недубли.',
            ],
            gain: [
                'В основную воронку не попадает мусор, а дубли остаются в лидах. Сделка без компании пройти может: определить её удаётся не всегда.',
            ],
        };
    }

    // seam — покрытия смыкаются ровно.
    // Лид есть, но менеджер в него не заходит: значит он работает фильтром,
    // а не местом работы. Это и есть рекомендованная схема «Админ + Сделка».
    if (model.leadEnd >= 0 && !model.callsApp.inLead) {
        return {
            tone: 'success',
            headline:
                'Лид работает фильтром на входе — менеджер в него не заходит.',
            workplace,
            price: [
                'Кто-то должен разбирать лиды: компанию, ИНН и дубли смотрит администратор или руководитель.',
            ],
            gain: [
                'У менеджера всегда только один интерфейс.',
                'В основную воронку не попадает мусор. Сделка без компании пройти может — это исключение, но оно штатное.',
                'Неизвестные и необработанные заявки лежат в одном месте.',
            ],
        };
    }

    if (model.leadEnd < 0) {
        return {
            tone: 'success',
            headline: 'Весь процесс идёт в сделке. Лиды в нём не участвуют.',
            workplace,
            price: [
                'В воронку попадают неразобранные сущности — для дублей нужна отдельная стадия.',
            ],
            gain: [
                'У менеджера всегда только один интерфейс.',
                'Лиды остаются простым фильтром, менеджер распределяет их сам.',
            ],
        };
    }

    const handoff = stageLabel(definition, model.leadEnd);

    return {
        tone: 'success',
        headline: handoff
            ? `Чистая граница: лид доводит клиента до «${handoff}», дальше его ведёт сделка.`
            : 'Чистая граница: лид и сделка стыкуются без нахлёста.',
        workplace,
        price: [
            'Менеджеру нужно освоить два места работы — переход между ними берёт на себя хук ХО.',
        ],
        gain: [
            'В основную воронку не попадает мусор. Сделка без компании пройти может — это исключение, но оно штатное.',
            'Неизвестные и необработанные заявки лежат в одном месте.',
        ],
    };
};
