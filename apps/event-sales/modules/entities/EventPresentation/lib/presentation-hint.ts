/**
 * Подсказки к отметке «презентация проведена». Данные отдельно от UI.
 *
 * Отметка проставляется САМА — когда менеджер отчитывается по событию
 * «Презентация» и жмёт «Результативно». Без объяснения это выглядит как
 * чужое решение: непонятно, откуда галочка и что будет, если её снять.
 * А цена ошибки высокая: презентация — ключевой показатель, и засчитанный
 * «на всякий случай» звонок портит и отчётность, и планы менеджера.
 *
 * Поэтому текст всегда отвечает на три вопроса: почему отмечено, что будет,
 * если оставить, и что делать, если презентации не было.
 */

export interface PresentationHint {
    title: string;
    /** Абзацы подсказки: почему так и что делать. */
    lines: string[];
}

/** Отмечено: объясняем, откуда галочка и как её снять. */
const DONE_PLANNED: PresentationHint = {
    title: 'Презентация засчитана',
    lines: [
        'Отмечено потому, что вы отчитываетесь по событию «Презентация» и указали «Результативно».',
        'Если презентация действительно состоялась — оставьте как есть.',
        'Если вместо презентации был просто хороший разговор и засчитывать его как презентацию не нужно — отожмите кнопку: событие уйдёт в отчёт как результативный звонок.',
        'Если презентации не было вовсе — вернитесь и укажите «Нерезультативно».',
    ],
};

/** Отмечено вручную по непрезентационному событию. */
const DONE_UNPLANNED: PresentationHint = {
    title: 'Презентация засчитана',
    lines: [
        'Вы отметили, что провели презентацию, хотя событие планировалось другим — она уйдёт в отчёт как спонтанная.',
        'Если презентации не было, а был обычный разговор — отожмите кнопку: событие засчитается как результативный звонок.',
    ],
};

/** Не отмечено на презентационном событии. */
const NOT_DONE_PLANNED: PresentationHint = {
    title: 'Презентация не засчитана',
    lines: [
        'Событие планировалось как презентация, но она пока не отмечена проведённой.',
        'Провели — нажмите: событие уйдёт в отчёт как презентация.',
        'Не провели, но разговор состоялся — оставьте как есть, это будет результативный звонок.',
        'Разговора не было — укажите «Нерезультативно».',
    ],
};

/** Не отмечено на обычном событии — можно засчитать спонтанную. */
const NOT_DONE_UNPLANNED: PresentationHint = {
    title: 'Провели презентацию?',
    lines: [
        'Событие планировалось не как презентация, но если вы её провели — нажмите, и она засчитается как спонтанная.',
        'Обычный разговор отмечать не нужно.',
    ],
};

export const getPresentationHint = (
    isDone: boolean,
    isPresentationTask: boolean,
): PresentationHint => {
    if (isDone) return isPresentationTask ? DONE_PLANNED : DONE_UNPLANNED;
    return isPresentationTask ? NOT_DONE_PLANNED : NOT_DONE_UNPLANNED;
};
