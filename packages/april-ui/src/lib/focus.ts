/**
 * Пришёл ли фокус С КЛАВИАТУРЫ (Tab/стрелки), а не программно или мышью.
 *
 * Зачем: модальные окна (Radix Dialog) при открытии сами уводят фокус на
 * ПЕРВЫЙ интерактивный элемент внутри — `focusFirst(getTabbableCandidates)`.
 * Для шкал-выборов (StepChoiceBar/LiquidChoiceBar) этим элементом
 * оказывается ПЕРВАЯ ступень, и подвешенное на `focus` превью «что будет
 * при клике» включалось само собой: окно показывало не текущее значение, а
 * первую ступень шкалы. `:focus-visible` — ровно та граница, которая
 * отличает намеренный клавиатурный фокус от такого перевода.
 *
 * jsdom и старые движки псевдокласс не знают и бросают на `matches` —
 * считаем такой фокус неклавиатурным (превью просто не включится).
 */
export const isKeyboardFocus = (element: Element | null): boolean => {
    if (!element) return false;
    try {
        return element.matches(':focus-visible');
    } catch {
        return false;
    }
};
