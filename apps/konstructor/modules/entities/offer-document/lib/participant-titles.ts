/**
 * Названия вариантов для подсказки «В КП войдут варианты: …». Подсказка нужна,
 * когда участников больше одного: единственный участник (режим «по одному» или
 * один вариант в режиме «вместе») ничего менеджеру не добавляет, он и так
 * видит открытый вариант. Участников нет или один — пустой список.
 */
export const offerParticipantTitles = (variants: readonly { title: string }[]): string[] =>
    variants.length > 1 ? variants.map(variant => variant.title) : [];
