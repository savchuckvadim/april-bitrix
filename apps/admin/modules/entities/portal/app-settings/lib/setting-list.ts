/**
 * Значение-список настройки приложения.
 *
 * Бэк помечает такую настройку `isList: true` и отдаёт справочник
 * допустимых кодов в `options`; в JSON портала значение лежит одной
 * строкой — CSV кодов. Разбор и сборка живут здесь, потому что это формат
 * САМОЙ настройки: любой раздел админки, который показывает такой ключ,
 * обязан читать и писать его одинаково.
 */

/**
 * Значение настройки → коды.
 *
 * Тип входа шире обещанного: в сгенерированном контракте `value` описан
 * объектом-или-null, а приезжает строкой. Всё, что не строка, читается как
 * пустой список — это то же самое, что «ключ не задан».
 */
export const parseSettingList = (raw: unknown): string[] => {
    if (typeof raw !== 'string') return [];
    return [
        ...new Set(
            raw
                .split(',')
                .map(value => value.trim())
                .filter(Boolean),
        ),
    ];
};

/**
 * Коды → значение настройки; `null` — сбросить ключ на дефолт.
 *
 * Пустой список сохраняется именно сбросом: «ключ задан пустым» и «ключ не
 * задан» бэк различает признаком `stored`, и настройка, которая ничего не
 * значит, не должна выглядеть настроенной.
 */
export const formatSettingList = (codes: readonly string[]): string | null =>
    codes.length > 0 ? codes.join(',') : null;
