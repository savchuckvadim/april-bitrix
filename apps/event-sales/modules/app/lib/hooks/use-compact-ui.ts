'use client';

import { useAppSelector } from './redux';

/**
 * Компактный режим интерфейса — по плейсменту, а не по каждому компоненту.
 *
 * Во вкладке карточки сущности (`*_DETAIL_TAB`) приложению отведён блок
 * ~630×600: там всё должно быть в одну строку и без крупных заголовков.
 * В полноэкранных встройках (таймлайн, отдельная страница) место есть —
 * компактим только второстепенное (например, записи звонков) точечно,
 * передавая `compact` руками.
 *
 * Правило одно на приложение: компонент спрашивает хук, а не парсит placement.
 */
export const useCompactUi = (): boolean =>
    useAppSelector(s =>
        Boolean(s.app.bitrix.placement?.placement?.includes('DETAIL_TAB')),
    );
