/**
 * Параметры наблюдения за операцией отправки.
 *
 * Пока это поллинг: бэкенд шлёт и WS-события (`event-sales-flow:done|error`),
 * но WSClient в этом приложении ходит на дефолтный хост монолита, а не на
 * event-sales, — до настройки хоста опрос статуса остаётся единственным
 * достоверным каналом. Когда WS подключим, поллинг станет фолбэком, а не
 * основным путём: интервалы ниже рассчитаны именно на такую роль.
 */

/** Пауза между опросами статуса в первые секунды после отправки. */
export const FLOW_POLL_INTERVAL_MS = 1500;

/**
 * Ступени паузы: чем дольше ждём, тем реже спрашиваем.
 *
 * Обычный отчёт исполняется за секунды — первые опросы частые, чтобы финиш
 * не запаздывал. Но если очередь занята и отчёт ждёт минуту-другую, опрос
 * раз в полторы секунды ничего не ускоряет, а только держит соединения и
 * добавляет серверу до 120 запросов на один отчёт (разбор нагрузки
 * 05.10.2026). С этими ступенями за те же три минуты уходит около сорока.
 */
const FLOW_POLL_STEPS: ReadonlyArray<{ untilMs: number; delayMs: number }> = [
    { untilMs: 9_000, delayMs: FLOW_POLL_INTERVAL_MS },
    { untilMs: 30_000, delayMs: 3_000 },
];

/** Пауза для опросов после последней ступени. */
const FLOW_POLL_SLOW_DELAY_MS = 5_000;

/** Пауза перед следующим опросом — по тому, сколько уже ждём исход. */
export const getFlowPollDelayMs = (elapsedMs: number): number =>
    FLOW_POLL_STEPS.find(step => elapsedMs < step.untilMs)?.delayMs ??
    FLOW_POLL_SLOW_DELAY_MS;

/**
 * Сколько всего ждём исход. Больше — бессмысленно: очередь либо отработала,
 * либо застряла, и человеку честнее сказать «проверь список», чем крутить
 * спиннер бесконечно.
 */
export const FLOW_POLL_TIMEOUT_MS = 3 * 60 * 1000;

export const FLOW_POLL_TIMEOUT_MESSAGE =
    'Отчёт принят, но подтверждение не пришло за три минуты. ' +
    'Проверьте список событий — скорее всего, всё применилось.';
