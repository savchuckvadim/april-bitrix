/**
 * Ключ ответа — пара «код анкеты : код вопроса».
 *
 * Ключом был код ПОЛЯ, и это работало ровно до портального каталога: одно и
 * то же поле осознанно спрашивается в разных анкетах (возражение — и в
 * плане, и в отчёте), а два вопроса, делящих ключ, делят и значение, и
 * статус «сохранено», и таймер автосохранения. Со встроенным составом это
 * ещё было осознанным решением, с портальным стало бы ошибкой данных:
 * админ, поставивший одно поле в две анкеты, не подписывался на то, что
 * ответы в них — один и тот же ответ.
 *
 * Пара уникальна по построению: коды анкет уникальны в каталоге, коды
 * вопросов — внутри анкеты (дубли и там, и там выбрасывает нормализатор).
 *
 * Живёт в слайсе каталога, а не в движке чек-листов: ключ строят оба —
 * движок (значения, черновики, таймеры) и сборка payload отправки
 * (dto-канал), и расхождение между ними теряло бы ответы молча.
 */
export const answerKey = (
    questionnaireCode: string,
    itemCode: string,
): string => `${questionnaireCode}:${itemCode}`;
