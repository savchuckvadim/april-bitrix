import type { AppGetState, RootState } from '@/modules/app/model/store';
// Прямые пути: барели слайса каталога и движка чек-листов тянут транспорт и UI.
import { waitForQuestionnaireCatalog } from '@/modules/entities/Questionnaire/lib/questionnaire-wait';
import { selectIncompleteInlineChecklists } from '@/modules/features/CallChecklist/lib/checklist-selectors';

/**
 * Участие портального каталога анкет в отправке отчёта.
 *
 * Единственное место, где записана ПОЛИТИКА ДЕГРАДАЦИИ, — и цепочка
 * отправки (`SendThunk.send`), и валидация (`send-validation.validateSend`)
 * ходят сюда, чтобы политика не разъехалась по двум файлам:
 *
 * 1. Ждём каталог ТОЛЬКО пока он грузится и ТОЛЬКО до дедлайна (1500 мс,
 *    `waitForQuestionnaireCatalog`).
 * 2. Не дождались, ошибка бэка, чужой контракт, пустой ответ — действует
 *    встроенный набор (`FALLBACK_CATALOG`), и отправка идёт ДАЛЬШЕ.
 * 3. Блокирующего гейта нет ни в одном состоянии каталога: отправку
 *    останавливает незаполненный обязательный ВОПРОС того состава, который
 *    действует на момент решения, а не недоступность каталога.
 *
 * Почему именно так: каталог — источник вопросов, а не разрешения сдать
 * отчёт. Блокирующее ожидание положило бы отправку отчётов на всех
 * порталах от одного 500 на бэке (а сегодня, пока миграция не накатана,
 * эндпоинт отвечает ошибкой ВСЕГДА — fallback это не теория, а рабочий
 * режим).
 */

/**
 * Дождаться каталога перед решением, что спрашивать. Зовётся ПЕРВЫМ шагом
 * send() — раньше валидации: состав анкет решает, какие вопросы
 * обязательны, и валидация на полсекунды более старом каталоге пропустила
 * бы незаполненную портальную анкету.
 *
 * Никогда не бросает и ничего не возвращает: решение принимает уже
 * следующий шаг по состоянию стора.
 */
export const awaitQuestionnaireCatalog = async (
    getState: AppGetState,
): Promise<void> => {
    await waitForQuestionnaireCatalog(getState);
};

/**
 * Текст ошибки «анкета не заполнена» — или null, если отправке ничего не
 * мешает. Считается по ДЕЙСТВУЮЩЕМУ составу (портальный, если доехал,
 * встроенный иначе), одинаково в валидации и в окне предпроверки.
 *
 * Вопросы обеих колонок: обязательный пункт блокирует отправку независимо
 * от того, в плане его спрашивают или в отчёте.
 */
export const getChecklistGateError = (state: RootState): string | null => {
    const incomplete = selectIncompleteInlineChecklists(state);
    if (incomplete.length === 0) return null;
    return `Заполните: ${incomplete
        .map(def => def.title.toLowerCase())
        .join(', ')}`;
};
