import type { RootState } from '@/modules/app/model/store';
import { selectQuestionnaireDefs } from '@/modules/entities/Questionnaire/model/selectors';
import {
    checklistFieldRefs,
    findChecklistOptionByCode,
    hasChecklistChoice,
} from './checklist-values';
import type { ChecklistFieldDef } from '../type/call-checklist.type';

/**
 * Ответы канала `smart` — КОНВЕРТОМ для payload отправки.
 *
 * Четвёртый канал наравне с `crm`, `dto` и `text`. Его особенность одна, и
 * из неё следует всё остальное: ответ адресован полю ЭЛЕМЕНТА смарта
 * (презентации, ЗПР), а элемента на момент ответа ещё не существует — его
 * создаёт или закрывает поток этого самого отчёта. Писать некуда, искать
 * нечего: ответ копится в стейте и уезжает вместе с отчётом, а раскладывает
 * его по полям бэк — он один знает id элемента, который сам же и родил
 * (включая спонтанный, для незапланированной презентации).
 *
 * ЧТО ИМЕННО ЕДЕТ. Конверт адресуется КОДАМИ каталога — «анкета, вопрос,
 * значение», — а не именами полей и не идентификаторами Битрикса. Причина
 * не в экономии: UF-имя поля и id элемента справочника смарта — адреса
 * чужой системы, они меняются без нашего ведома (поле переименовали,
 * справочник пересобрали), и фрейм, который их везёт, начал бы врать молча.
 * Коды каталога — наши, и их правда лежит там же, где состав вопросов.
 *
 * ЗНАЧЕНИЕ — в каноне каталога, ровно как оно лежит в стейте: `YYYY-MM-DD`
 * у дат, `Y`/`N` у «да/нет», код варианта у справочника. Перевод в формат
 * Битрикса (`DD.MM.YYYY`, `1`/`0`, числовой id элемента) делает бэк по
 * живому смарту портала — там же, где он резолвит и само поле.
 *
 * Каталог обходится ЦЕЛИКОМ, как у dto- и text-ответов: ответ существует,
 * только если менеджер его дал, а активность анкеты к моменту отправки
 * могла смениться (предикт стадии пересчитывается) — выбрасывать уже данный
 * ответ из-за этого нельзя.
 */

/** Одна пара «вопрос — ответ» в конверте отправки. */
export interface ChecklistSmartAnswer {
    /** Код анкеты портального каталога. */
    questionnaire: string;
    /** Код вопроса внутри анкеты. */
    item: string;
    /** Ответ в каноне каталога; пустых в конверте не бывает. */
    value: string;
}

export const selectChecklistSmartAnswers = (
    state: RootState,
): ChecklistSmartAnswer[] => {
    const answers: ChecklistSmartAnswer[] = [];

    for (const def of selectQuestionnaireDefs(state)) {
        // Ключи ответов собирает общий перечислитель вопросов: писатель
        // (движок) и читатель (конверт) обязаны строить их одинаково —
        // расхождение теряло бы ответы молча.
        for (const ref of checklistFieldRefs(def)) {
            const item = ref.def;
            if (item.channel !== 'smart') continue;
            const value = state.callChecklist.valueByKey[ref.answerKey] ?? '';
            // Пустой ответ — это не ответ: в элемент он уехал бы пустой
            // строкой поверх поля, которое мог заполнить кто-то другой.
            if (!value.trim()) continue;
            answers.push({
                questionnaire: def.code,
                item: item.code,
                value: toSmartAnswerValue(item, value),
            });
        }
    }

    return answers;
};

/**
 * Ответ в конверт. Значение из стейта уходит КАК ЕСТЬ — кроме строки со
 * своим списком формулировок.
 *
 * Почему исключение. У такого вопроса поле в Битриксе обычное строковое, а
 * варианты объявил сам пункт анкеты (`string` + `options`): в стейте
 * держится КОД варианта, на нём стоит выбор в селекте, но записывается
 * всегда название — карточку элемента читают люди, и `pay_now` в поле
 * «Обещание клиента» был бы мусором. Ровно это правило уже действует на
 * канале `crm` (`toPortalFieldValue`), и разъезжаться двум каналам в одном
 * и том же вопросе незачем.
 *
 * Справочника (`enumeration`) это не касается: там в конверт уезжает код
 * варианта, а в id элемента списка его переводит бэк — по живому
 * справочнику смарта, а не по слепку каталога.
 */
const toSmartAnswerValue = (item: ChecklistFieldDef, value: string): string => {
    if (!hasChecklistChoice(item)) return value;
    return findChecklistOptionByCode(item.options, value)?.title ?? value;
};
