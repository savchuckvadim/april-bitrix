/**
 * Условия обслуживания. Часть строк зависит от цен конкретного клиента,
 * поэтому список собирается под предложение, а не лежит константой.
 */
export function buildTerms(offer: RenewalOffer): readonly string[] {
    const terms: string[] = [];

    if (offer.devIncluded && offer.devHours > 0) {
        terms.push(
            `${formatHours(
                offer.devHours,
            )} разработки в месяц входят в пакет: доработки под ваши задачи делаем без дополнительной оплаты.`,
        );
        terms.push(
            `Сверх этих часов — ${formatRub(
                offer.devHourPrice,
            )} за час, по согласованной оценке до начала работ.`,
        );
    } else if (offer.devIncluded) {
        terms.push(
            `Разработка — ${formatRub(
                offer.devHourPrice,
            )} за час, по согласованной оценке до начала работ.`,
        );
    }

    terms.push('Обновления приложений и исправления ошибок входят в стоимость.');
    terms.push('Поддержка — в рабочее время, через чат Битрикс24.');

    return terms;
}
