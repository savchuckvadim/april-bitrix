/**
 * Якоря оценок и материалы методики: типы и тексты вкладок формы. Поля
 * `sectionAnchors` и `knowledge` в сгенерированном клиенте описаны как
 * произвольные объекты — здесь их точная форма по DTO бэкенда.
 */

/** Раздел → полоса шкалы («1-2» … «9-10») → описание словами. */
export type MethodologyAnchors = Record<string, Record<string, string>>;

/** Вид базы знаний → чей документ: общий или этой методики. */
export type MethodologyKnowledge = Record<string, string>;

/** Слой «общий документ» — как в конфиге бэкенда. */
export const KNOWLEDGE_LAYER_SHARED = 'shared';

/**
 * Вид базы знаний, который методика может объявить своим (каталог формы).
 * В сгенерированном клиенте поля ещё нет — описан руками до перегенерации.
 */
export interface CatalogKnowledgeKind {
    kind: string;
    title: string;
    /** Сколько знаков вида получает проход методики. */
    budgetChars: number;
    /** Вид читается только у показов, звонков по решению и доработки. */
    presentationOnly: boolean;
}

