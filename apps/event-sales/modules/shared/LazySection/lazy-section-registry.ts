/**
 * Какие секции «по требованию» менеджер уже раскрыл в этом фрейме.
 *
 * Живёт в памяти модуля — на время жизни фрейма. Экран списка и экран дела
 * пересоздаются при каждом переходе, и без этой памяти раскрытая «История»
 * схлопывалась бы обратно после каждого возврата к списку.
 *
 * В хранилище браузера НЕ пишем намеренно: раскрытие — это запросы к
 * порталу, и «запомнить навсегда» вернуло бы загрузку на каждое открытие
 * фрейма, ради отказа от которой секции и сделаны ленивыми.
 */
const opened = new Set<string>();

export const isLazySectionOpened = (id: string): boolean => opened.has(id);

export const markLazySectionOpened = (id: string): void => {
    opened.add(id);
};

/** Сброс — для тестов. */
export const resetLazySectionsForTests = (): void => {
    opened.clear();
};
