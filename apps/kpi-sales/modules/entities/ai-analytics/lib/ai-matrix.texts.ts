import { aiByCallsLabel } from './ai-metric.util';
import { formatAiFullDate } from './ai-period-label.util';
import { pluralRu } from './ai-readiness.data';
import { formatAiScore } from './ai-score.util';

/*
 * Тексты ячеек матриц KPI-вида «AI: типы звонков» и «AI: разделы оценки
 * по типу» (решение владельца 20.10.2026): крупно — оценка из 10, мелко —
 * по скольким звонкам; при нехватке разборов — «ещё N» до оценки; при
 * 8–19 — «предварительно»; цвет — выше/ниже среднего по отделу. Пороги
 * объёма — AI_METRIC_THRESHOLDS (ai-metric.util), здесь только слова.
 */

/** Шкала оценки разбора. */
export const AI_MATRIX_SCORE_MAX = 10;

/**
 * Порог «выше / ниже среднего по отделу» в баллах: разница меньше — «около
 * среднего», без цвета. Бэк порога не отдаёт; число — решение владельца
 * 20.10.2026 (inv_matrices-ux, пункт 5).
 */
export const AI_MATRIX_NORM_DELTA = 0.5;

const MANAGER_FORMS = ['сотр.', 'сотр.', 'сотр.'] as const;

export const AI_MATRIX_TEXT = {
    firstCell: 'Менеджер',
    totalsRow: 'Итого по отделу',
    /** Сводная колонка матрицы разделов: оценка типа (или всех типов). */
    sectionsTotal: 'Итог',
    /** Звонков этого типа у сотрудника за период нет. */
    noCalls: '—',
    /** Крупно при нехватке разборов: «ещё 4». */
    remaining: (left: number) => `ещё ${left}`,
    remainingNote: 'до оценки',
    preliminary: 'предварительно',
    byCalls: (n: number) => aiByCallsLabel(n),
    managers: (count: number) =>
        `${count} ${pluralRu(count, MANAGER_FORMS)}`,
    /** «6,8 из 10» — в строке «Итого по отделу». */
    scoreOutOf: (score: number) =>
        `${formatAiScore(score)} из ${AI_MATRIX_SCORE_MAX}`,
    /** Разборов хватает, а оценки нет (старый расчёт или из ячеек не сложить). */
    noScore: 'оценки нет',
    hint: {
        fewData: (
            n: number,
            minN: number,
            comparableFrom: string | null,
        ): string =>
            [
                `Разобрано ${n} ${pluralRu(n, ['звонок', 'звонка', 'звонков'])} этого вида. Оценку показываем от ${minN} — на меньшем числе один неудачный разговор меняет картину.`,
                comparableFrom
                    ? `Что сделать: выберите период длиннее (но не раньше ${formatAiFullDate(comparableFrom)}).`
                    : 'Что сделать: выберите период длиннее.',
            ].join('\n'),
        low: (lowMax: number): string =>
            `Меньше ${lowMax} разборов — ориентир, а не вывод. Сравнивать сотрудников по этому числу рано.`,
        norm: {
            above: (norm: number) =>
                `Выше среднего по отделу (${formatAiScore(norm)}).`,
            below: (norm: number) =>
                `Ниже среднего по отделу (${formatAiScore(norm)}).`,
            near: (norm: number) =>
                `Около среднего по отделу (${formatAiScore(norm)}).`,
        },
        /** Оценка корзины или «всех типов» сложена только из частей с оценкой. */
        partialScore:
            'Оценка сложена из видов звонков, у которых она есть; виды с меньшим числом разборов в неё не вошли.',
        /** В итоге есть разборы, а оценки нет: у каждого сотрудника их меньше порога. */
        noCellScores: (minN: number) =>
            `У каждого сотрудника меньше ${minN} разборов — среднее по отделу из ячеек не сложить.`,
        /** Корзина или «все типы» без оценки: у каждого вида звонков разборов меньше порога. */
        noPartScores: (minN: number) =>
            `Оценка складывается из видов звонков, у которых она есть; пока у каждого вида меньше ${minN} разборов.`,
        /** Строка «Итого по отделу»: с чем сравниваются ячейки выше. */
        totalsRow:
            'Средняя по всем разборам выбранных сотрудников — с ней сравниваются строки выше.',
        /** Оценка не сохранена старым расчётом. */
        legacy:
            'Разборов хватает, но оценка в этом сохранённом расчёте не записана. Появится после пересчёта — попросите разработчика.',
    },
    csv: {
        score: 'оценка',
        calls: 'разборов',
        remaining: (left: number) => `ещё ${left} до оценки`,
    },
} as const;
