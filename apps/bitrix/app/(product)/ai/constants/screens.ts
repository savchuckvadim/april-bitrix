/**
 * Задание на съёмку скринов раздела «AI для отдела продаж».
 *
 * В главах стоят рамки с подписью «СКРИН: …» — картинок ещё нет. Этот файл
 * держит список того, что нужно снять: идентификаторы совпадают с картой
 * фактов (`back/ai/tasks/ai-kb-facts.md`, список «и»), поэтому снятое
 * раскладывается по местам без гаданий.
 *
 * Каждая глава добавляет сюда свой массив и не трогает чужие. Один и тот же
 * скрин, нужный двум главам, остаётся одной записью — главы перечисляются
 * в `pages`.
 */

import type {
    TheoryBlock,
    TheoryScreenAspect,
} from '../../process/_core/theory-types';

export interface AiScreen {
    /** Идентификатор из карты фактов: по нему скрин ищут и переиспользуют. */
    id: string;
    /** Где снимать: интерфейс и место в нём. */
    where: string;
    /** Что должно попасть в кадр. */
    what: string;
    /** Главы раздела, где стоит место под этот скрин. */
    pages: string[];
}

/**
 * Место под скрин по идентификатору из списка.
 *
 * Подпись под рамкой берётся из реестра, а не пишется в главе второй раз:
 * иначе задание на съёмку и текст под картинкой разъедутся уже на втором
 * уточнении.
 */
export const aiScreenBlock = (
    screens: readonly AiScreen[],
    id: string,
    aspect: TheoryScreenAspect = '16:9',
): TheoryBlock => ({
    kind: 'screen',
    label: screens.find(screen => screen.id === id)?.what ?? id,
    aspect,
});

