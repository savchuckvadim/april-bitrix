import type { PortalQuestionnaireListItem } from '../model';

/**
 * Код анкеты — стабильный ключ, по которому фрейм узнаёт набор ответов.
 *
 * Владелец его не печатает: код предлагается транслитом названия и дальше
 * не меняется. Причина не в удобстве — пара «приложение + код» адресует
 * анкету на бэке (сохранение делает upsert именно по ней), и правка кода у
 * живой анкеты означала бы, что уже собранные ответы прилетают под чужим
 * ключом.
 */

/** Кириллица → латиница; таблица покрывает то, из чего складываются коды. */
const TRANSLIT: Record<string, string> = {
    а: 'a',
    б: 'b',
    в: 'v',
    г: 'g',
    д: 'd',
    е: 'e',
    ё: 'e',
    ж: 'zh',
    з: 'z',
    и: 'i',
    й: 'y',
    к: 'k',
    л: 'l',
    м: 'm',
    н: 'n',
    о: 'o',
    п: 'p',
    р: 'r',
    с: 's',
    т: 't',
    у: 'u',
    ф: 'f',
    х: 'h',
    ц: 'c',
    ч: 'ch',
    ш: 'sh',
    щ: 'sch',
    ъ: '',
    ы: 'y',
    ь: '',
    э: 'e',
    ю: 'yu',
    я: 'ya',
};

/** Длина кода: он показывается в списке и в логах фрейма. */
const MAX_LENGTH = 48;

/**
 * Произвольное название → латинский код без длины: буквы, цифры и
 * подчёркивание.
 *
 * Живёт отдельно от кода анкеты, потому что тем же транслитом собирается
 * код ПОЛЯ, которое админка заводит в Битриксе, — а у него своя длина и
 * свой регистр (см. `lib/field-create-view.ts`). Две таблицы транслита
 * означали бы, что одно и то же название превращается в разные коды.
 */
export const toLatinSlug = (raw: string): string =>
    raw
        .trim()
        .toLowerCase()
        .split('')
        .map(char => (char in TRANSLIT ? TRANSLIT[char] : char))
        .join('')
        .replace(/[^a-z0-9]+/g, '_')
        .replace(/^_+|_+$/g, '');

/**
 * Название анкеты → её код.
 *
 * Пусто на входе (или название из одних символов, которым нет латинской
 * пары) даёт пустую строку: подставлять `questionnaire_1` нельзя — код
 * должен читаться глазами рядом с ответами, а проверка черновика и так
 * скажет, что название обязательно.
 */
export const toQuestionnaireCode = (title: string): string =>
    toLatinSlug(title).slice(0, MAX_LENGTH).replace(/_+$/g, '');

/**
 * Анкета того же приложения, которую перезапишет сохранение.
 *
 * Создание на бэке — upsert по паре «приложение + код»: анкета с занятым
 * кодом не будет отвергнута, она молча заменит существующую вместе с её
 * составом. Поэтому совпадение ищется до сохранения, а не после.
 */
export const findQuestionnaireCodeConflict = (
    list: PortalQuestionnaireListItem[] | undefined,
    appCode: string,
    code: string,
    currentId?: string | null,
): PortalQuestionnaireListItem | null => {
    const normalized = code.trim();
    if (!normalized) return null;

    return (
        (list ?? []).find(
            item =>
                item.appCode === appCode &&
                item.code === normalized &&
                item.id !== currentId,
        ) ?? null
    );
};

/** Что мешает проверить занятость кода: список анкет — единственный её источник. */
export type QuestionnaireCodeGuard = 'pending' | 'failed';

/**
 * Почему занятость кода ещё не проверена; `null` — список анкет прочитан.
 *
 * Молчащий список — это не «код свободен», а «мы не знаем»: пустой результат
 * поиска конфликта у непрочитанного списка неотличим от честного «код
 * свободен». Разница дорогая — создание на бэке делает upsert по паре
 * «приложение + код», и сохранение под занятым кодом заменило бы чужую
 * анкету вместе с её составом. Поэтому пока список не прочитан, создание
 * запирается.
 *
 * У сохранённой анкеты запирать нечего: правка уходит по её `id`, а код и
 * приложение read-only — заменить чужую анкету ей нечем.
 */
export const questionnaireCodeGuard = (
    isNew: boolean,
    list: { isSuccess: boolean; isError: boolean },
): QuestionnaireCodeGuard | null => {
    if (!isNew || list.isSuccess) return null;
    return list.isError ? 'failed' : 'pending';
};
