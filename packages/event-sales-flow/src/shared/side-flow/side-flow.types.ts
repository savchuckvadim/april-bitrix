// package-adapted: серверная голова отрезана — FlowBitrix (тип поверх PBXService) живёт у воркеров сайд-очередей; чистым билдерам пакета нужны имена потоков и адреса KPI-строк
/**
 * Какой сайд-поток работает — он же префикс ключа гейта и префикс лога
 * общих сервисов раздела.
 */
export type SideFlowName = 'pres-flow' | 'zpr-flow';

/**
 * Префикс строки лога общего сервиса.
 *
 * Зачем. Общие сервисы (привязка к задаче, дотяжка сделки) не знают, кто
 * их позвал, а по логу это должно быть видно: до переезда в раздел канал
 * грепался по потоку (`[zpr-flow]`, `[pres-flow]`), и общий `[side-flow]`
 * эту возможность отнял — по строке «дотяжка не удалась» было уже не
 * понять, чей отчёт её не дотянул.
 *
 * Поток не назван (легаси-вызов) — остаётся прежний общий `[side-flow]`:
 * лог менее точен, но джоб из-за этого не меняется.
 */
export const sideFlowLogTag = (flow?: SideFlowName): string =>
    `[${flow ?? 'side-flow'}]`;

/**
 * Строка KPI/History-списка, созданная отчётом, — адрес обратной ссылки
 * элемента смарта: сайд-очередь дописывает `T{hex}_{id}` в её
 * multiple-crm-поле (`crmFieldId`). Плановый элемент едет в план-строки,
 * отчётный — в отчётные (решение владельца 31.08).
 */
export interface SmartKpiRowRef {
    iblockId: number;
    elementId: number;
    crmFieldId: string;
}

/** Строки, разложенные по назначению элемента смарта. */
export interface SmartKpiRowRefs {
    plan: SmartKpiRowRef[];
    report: SmartKpiRowRef[];
}
