/** Настройки старта фрейма (`Bitrix.start`) */
export interface BitrixInitOptions {
    /**
     * Не ждать `user.current`. Старт возвращается сразу после поднятия фрейма:
     * домен, placement и auth-данные уже известны, пользователь грузится
     * рядом. Приложение дожидается его через `api.whenUser()` там, где он
     * нужен, а до этого запускает то, чему хватает домена.
     *
     * По умолчанию выключено — старт ждёт пользователя, как раньше:
     * приложения включают опцию по одному, когда готовы не читать
     * пользователя сразу после `start`.
     */
    deferUser?: boolean;
}
