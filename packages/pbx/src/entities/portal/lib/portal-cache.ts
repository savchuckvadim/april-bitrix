import {
    SWR_DAY_MS,
    expireSwrCache,
    getConfig,
    removeOldPortalCache,
} from '@workspace/api';
import type { SwrCacheKey } from '@workspace/api';
import type { Portal } from '../type/portal-type';

/** Логическое имя записи слепка внутри ключа кэша. */
const PORTAL_CACHE_ENTRY = 'portal';

/**
 * Версия схемы значения. Поднимать, когда меняется ФОРМА слепка
 * (`type/portal-type.ts`): записи прошлой версии перестают читаться сами,
 * приложение молча уходит в сеть за новой формой.
 */
export const PORTAL_CACHE_VERSION = 1;

/**
 * Срок годности слепка — сутки.
 *
 * Слепок портала меняется только при install полей/списков, то есть
 * считаные разы в год: держать его сутки и раз в день тихо перепроверять —
 * ровно то, что просил владелец. Быстрее нужно не по расписанию, а по
 * событию — для этого есть `expirePortalCache` (кнопка ⟳).
 *
 * Внимание: это НЕ «через сутки данные пропадут». Через сутки запись просто
 * помечается протухшей: она отдаётся мгновенно, а обновление идёт фоном и
 * при неудаче оставляет прежний слепок жить дальше.
 */
export const PORTAL_CACHE_STALE_AFTER_MS = SWR_DAY_MS;

/**
 * Предельный возраст слепка — неделя. Старше — запись к отдаче не годна,
 * приложение обязано дождаться сети.
 *
 * Почему потолок задан здесь, а не оставлен на дефолт утилиты (30 дней):
 * у слепка особая цена ошибки — по его карте полей идут НЕОБРАТИМЫЕ записи
 * в CRM (`bitrix.deal.update(id, { [ufKey]: value })` в хвост-полях и
 * чек-листах). Пока фоновое обновление падает — сеть, `resultCode ≠ 0`,
 * сменившаяся форма ответа, — фрейм молча пишет по UF-ключам той давности,
 * какую разрешает потолок. В Битриксе переустановленное поле обычно
 * остаётся жить, поэтому запись пройдёт УСПЕШНО и уедет туда, где её уже
 * никто не читает: ни ошибки, ни отката.
 *
 * Неделя — компромисс в пользу владельца. Прежняя схема (суточный ключ
 * `portal_cache_<дата>`) умирала уже назавтра после падения бэка; неделя
 * спокойно переживает выходные и пару дней аварии. А неделя подряд упавших
 * обновлений — это уже инцидент, и остаться честно без слепка (тогда записи
 * просто не уходят: `findUfKey` не даёт ключа) безопаснее, чем писать по
 * устаревшей карте.
 */
export const PORTAL_CACHE_MAX_AGE_MS = 7 * SWR_DAY_MS;

/**
 * Сегмент приложения в ключе. `event-sales` и `event-service` в проде висят
 * на ОДНОМ origin (`/sales` и `/service`) и до сих пор делили одну ячейку
 * кэша слепка. Кто мы — говорит `setConfig({ appId })` в api-provider'е
 * приложения; без него остаётся нейтральный `pbx` (поведение как раньше —
 * общая ячейка, но уже с доменом и версией схемы в ключе).
 */
const getAppSegment = (): string => getConfig().appId || 'pbx';

/** Ключ записи слепка: приложение + домен + версия схемы. */
export const getPortalCacheKey = (domain: string): SwrCacheKey => ({
    name: `${getAppSegment()}:${PORTAL_CACHE_ENTRY}`,
    domain,
    version: PORTAL_CACHE_VERSION,
});

/**
 * Явная инвалидация слепка: «на портале переустановили поля, читай заново».
 *
 * Запись НЕ удаляется, а помечается протухшей — приложение продолжает
 * работать на прежнем слепке, пока не приедет новый. Именно этим новая схема
 * отличается от прежнего `clearPortalCache`, который сносил кэш ДО запроса и
 * при упавшем бэке оставлял фрейм вообще без конфигурации портала.
 */
export const expirePortalCache = (domain: string): Promise<boolean> =>
    expireSwrCache(getPortalCacheKey(domain));

/**
 * Ответ похож на слепок портала.
 *
 * Проверка нарочно грубая: пустой объект, страница-заглушка прокси или
 * `{ resultCode: ... }` без данных не должны затирать рабочий слепок, а
 * перечислять все поля здесь — значит ломать кэш на каждом расширении бэка.
 * Опора — то, на чём стоит весь резолв: наборы полей сущностей.
 */
export const isPortalSnapshot = (value: unknown): boolean => {
    if (!value || typeof value !== 'object') return false;

    const snapshot = value as Record<string, unknown>;
    const hasFields = (key: string): boolean => {
        const entity = snapshot[key] as Record<string, unknown> | undefined;
        return Boolean(entity && Array.isArray(entity.bitrixfields));
    };

    return hasFields('company') || hasFields('lead') || hasFields('bitrixDeal');
};

/**
 * Слепки совпадают.
 *
 * Сравнение по сериализации: слепок приходит целиком и без стабильного
 * номера версии, а стоит это несколько миллисекунд не чаще раза в сутки —
 * ровно тогда, когда фоновое обновление реально доехало. Цена ошибки выше:
 * лишний `setPortal` будит инициализацию компании, сбор контактов и гвард
 * чужой задачи, то есть пачку запросов в Битрикс на ровном месте.
 */
export const isSamePortalSnapshot = (a: Portal, b: Portal): boolean => {
    try {
        return JSON.stringify(a) === JSON.stringify(b);
    } catch {
        return false;
    }
};

/** Префикс ключей прошлой схемы (`portal_cache_<дата>`). */
const LEGACY_CACHE_PREFIX = 'portal_cache';

/** Легаси-ключи чистим один раз за сессию, а не на каждый запрос слепка. */
let legacySwept = false;

/**
 * Разовая уборка легаси-кэша (`portal_cache_<дата>`).
 *
 * После переезда на `swr-cache` эти записи никто не читает, а весят они
 * сотни килобайт на каждый прожитый день. Зовётся ПОСЛЕ того, как слепок уже
 * получен: даже здесь ничего не удаляется раньше, чем появилось новое.
 *
 * Метём ровно легаси-семантикой (`removeOldPortalCache` — всё, кроме ключа
 * за сегодня), а не подчистую: тот же префикс на общем origin пишет
 * konstructor по СВОЕЙ схеме, и сносить его сегодняшнюю запись — не наше
 * дело. Своё старьё так уберётся всё равно: назавтра вчерашний ключ уже не
 * «сегодняшний».
 */
export const sweepLegacyPortalCache = (): void => {
    if (legacySwept) return;
    legacySwept = true;

    removeOldPortalCache(LEGACY_CACHE_PREFIX);
};

/** Сброс разовых флагов модуля. Нужен тестам. */
export const resetPortalCacheRuntime = (): void => {
    legacySwept = false;
};
